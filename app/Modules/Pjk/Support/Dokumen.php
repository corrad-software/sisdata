<?php

namespace App\Modules\Pjk\Support;

use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Http\UploadedFile;
use PhpOffice\PhpSpreadsheet\Cell\Coordinate;
use PhpOffice\PhpSpreadsheet\Cell\DataType;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Writer\Xlsx;
use Symfony\Component\HttpFoundation\Response;

/** PDF / Excel output for receipts, letters, statements and reports (SRS-PJK-11/17/27). */
final class Dokumen
{
    /**
     * @param  list<array{tajuk?: string, jadual?: list<list<string>>, kepala?: list<string>, teks?: string}>  $sections
     */
    public static function pdf(string $title, array $sections, ?string $footer = null, bool $landscape = false): string
    {
        return Pdf::loadHTML(self::html($title, $sections, $footer))->setPaper('a4', $landscape ? 'landscape' : 'portrait')->output();
    }

    /** @param list<array{tajuk?: string, jadual?: list<list<string>>, kepala?: list<string>, teks?: string}> $sections */
    public static function html(string $title, array $sections, ?string $footer = null): string
    {
        $h = '<!doctype html><html><head><meta charset="utf-8"><style>body{font-family:DejaVu Sans,sans-serif;font-size:10px;color:#18181b}'
            .'h1{font-size:15px;margin:0 0 4px}h2{font-size:12px;margin:14px 0 4px}table{width:100%;border-collapse:collapse}'
            .'td,th{border:1px solid #d4d4d8;padding:4px;text-align:left;vertical-align:top}th{background:#f4f4f5}.p{white-space:pre-wrap;font-size:11px;line-height:1.5}'
            .'.k{margin-top:16px;color:#71717a;font-size:9px}</style></head><body>';
        $h .= '<p style="color:#2563eb;font-weight:bold">MAJLIS AGAMA ISLAM SELANGOR · SISDATA</p><h1>'.e($title).'</h1>';
        foreach ($sections as $s) {
            if (! empty($s['tajuk'])) {
                $h .= '<h2>'.e($s['tajuk']).'</h2>';
            }
            if (isset($s['teks'])) {
                $h .= '<div class="p">'.e($s['teks']).'</div>';
            }
            if (isset($s['jadual'])) {
                $h .= '<table>';
                if (! empty($s['kepala'])) {
                    $h .= '<tr>'.implode('', array_map(fn ($c) => '<th>'.e($c).'</th>', $s['kepala'])).'</tr>';
                }
                foreach ($s['jadual'] as $row) {
                    $h .= '<tr>'.implode('', array_map(fn ($c) => '<td>'.e((string) $c).'</td>', $row)).'</tr>';
                }
                $h .= '</table>';
            }
        }
        $h .= '<p class="k">'.e($footer ?? __('pjk::pjk.dokumen.dijana', ['masa' => now()->format('d/m/Y H:i')])).'</p></body></html>';

        return $h;
    }

    /**
     * @param  list<string>  $headers
     * @param  list<list<string|int|null>>  $rows
     */
    public static function xlsx(string $title, array $headers, array $rows): string
    {
        $book = new Spreadsheet;
        $sheet = $book->getActiveSheet();
        $sheet->setTitle(mb_substr(preg_replace('/[\\\\\/\?\*\[\]:]/', ' ', $title) ?? 'Laporan', 0, 31));
        foreach ($headers as $i => $head) {
            $sheet->setCellValue(Coordinate::stringFromColumnIndex($i + 1).'1', $head);
        }
        foreach ($rows as $r => $row) {
            foreach ($row as $c => $value) {
                $sheet->setCellValueExplicit(Coordinate::stringFromColumnIndex($c + 1).($r + 2), (string) ($value ?? ''), DataType::TYPE_STRING);
            }
        }
        $sheet->getStyle('A1:'.Coordinate::stringFromColumnIndex(max(1, count($headers))).'1')->getFont()->setBold(true);
        $tmp = tempnam(sys_get_temp_dir(), 'pjkx');
        (new Xlsx($book))->save($tmp);
        $out = (string) file_get_contents($tmp);
        @unlink($tmp);

        return $out;
    }

    /** Generated bytes as an UploadedFile for DocumentStore::store(). */
    public static function file(string $content, string $name, string $mime = 'application/pdf'): UploadedFile
    {
        $path = tempnam(sys_get_temp_dir(), 'pjkd');
        file_put_contents($path, $content);

        return new UploadedFile($path, $name, $mime, null, true);
    }

    public static function download(string $content, string $name, string $mime): Response
    {
        return response($content, 200, [
            'Content-Type' => $mime,
            'Content-Disposition' => 'attachment; filename="'.$name.'"',
        ]);
    }
}
